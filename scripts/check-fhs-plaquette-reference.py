"""Reproduce four bounded teaching references through the real public API.

--write refreshes only dist/fhs-plaquette-reference.js. The normal/--check path
checks that asset, strict metadata/input/schema and tight numeric equivalence.
The independent oracle uses piecewise analytic spinors and explicit modular
loops, never the production _fhs, np.roll, model or eigensolver routines.
"""
import argparse
import cmath
import copy
import hashlib
import json
import math
from pathlib import Path
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / ".openai/local-python-deps"))
sys.path.insert(0, str(ROOT / "dist/python"))
from browser_api import run

ASSET = ROOT / "dist/fhs-plaquette-reference.js"
PREFIX = "// Generated by scripts/check-fhs-plaquette-reference.py --write.\nexport const FHS_PLAQUETTE_REFERENCE="
SUFFIX = ";\n"
ATOL, RTOL = 2e-14, 2e-14
MODELS = [("qwz-minus-one", -1), ("qwz-plus-one", 1), ("qwz-trivial", 3), ("qwz-closing", -2)]
FORWARD = [(0, 1), (1, 2), (3, 2), (0, 3)]


def utf8_lf_bytes(text):
    return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


def close(a, b, path="number", tolerance=ATOL):
    assert isinstance(a, (int, float)) and not isinstance(a, bool), f"{path}: number required"
    assert math.isfinite(a) and math.isfinite(b), f"{path}: nonfinite number"
    assert math.isclose(a, b, rel_tol=RTOL, abs_tol=tolerance), f"{path}: {a} != {b}"


def strict(a, b, path="root"):
    assert type(a) is type(b), f"{path}: exact type differs"
    if isinstance(b, dict):
        assert a.keys() == b.keys(), f"{path}: exact fields differ"
        for key in b:
            strict(a[key], b[key], f"{path}.{key}")
    elif isinstance(b, list):
        assert len(a) == len(b), f"{path}: exact shape differs"
        for index, value in enumerate(b):
            strict(a[index], value, f"{path}[{index}]")
    else:
        assert a == b, f"{path}: exact value differs"


def complex_pair(value):
    assert isinstance(value, list) and len(value) == 2
    for part in value:
        close(part, part)
    return complex(*value)


def independent_state(x, y, mass):
    d = (math.sin(x), math.sin(y), mass+math.cos(x)+math.cos(y))
    radius = math.sqrt(math.fsum(v*v for v in d))
    assert radius > 0
    nx, ny, nz = (v/radius for v in d)
    if nz > -.9:
        denominator = math.sqrt(2*(1+nz))
        return complex(-nx, ny)/denominator, complex(1+nz, 0)/denominator
    denominator = math.sqrt(2*(1-nz))
    return complex(1-nz, 0)/denominator, complex(-nx, -ny)/denominator


def overlap(a, b):
    return sum(x.conjugate()*y for x, y in zip(a, b))


def independent_grid(size, mass):
    k = [-math.pi+2*math.pi*i/size for i in range(size)]
    u = [[independent_state(x, y, mass) for x in k] for y in k]
    rx = [[overlap(u[j][i], u[j][(i+1) % size]) for i in range(size)] for j in range(size)]
    ry = [[overlap(u[j][i], u[(j+1) % size][i]) for i in range(size)] for j in range(size)]
    fluxes = []
    for j in range(size):
        row = []
        for i in range(size):
            values = [rx[j][i], ry[j][(i+1) % size], rx[(j+1) % size][i].conjugate(), ry[j][i].conjugate()]
            assert min(abs(z) for z in values) > 1e-10
            row.append(-cmath.phase(math.prod(z/abs(z) for z in values)))
        fluxes.append(row)
    return k, rx, ry, fluxes


def verify_result(result):
    """Check a serialized result internally and against analytic projectors."""
    p, replay = result["parameters"], result["fhsReplay"]
    size, mass, strength = p["mesh"], p["mass"], p["gaugeStrength"]
    strict(replay["schemaVersion"], 1)
    strict(replay["mesh"], size)
    strict(replay["convergenceIndex"], 0)
    strict(replay["complexEncoding"], "[real,imag]")
    strict(replay["sewing"], "identity")
    strict(replay["orientation"], "kx then ky")
    strict(replay["linkThreshold"], 1e-10)
    strict(replay["bandIsolated"], result["topology"]["defined"])
    strict([cell["id"] for cell in replay["cells"]], ["interior", "boundary-xy"])
    assert replay["beforeLinksValid"] and replay["afterLinksValid"]
    k, rx, ry, fluxes = independent_grid(size, mass)
    if replay["bandIsolated"]:
        total = math.fsum(v for row in fluxes for v in row)/(2*math.pi)
        close(result["convergence"][0]["value"], total, "base Chern")
    else:
        assert result["topology"]["value"] is None
        assert result["convergence"][0]["value"] is None
    for number, cell in enumerate(replay["cells"]):
        j, i = (size//2, size//2) if number == 0 else (size-1, size-1)
        strict(cell["anchor"], [j, i])
        indices = [(j, i), (j, (i+1) % size), ((j+1) % size, (i+1) % size), ((j+1) % size, i)]
        assert len(cell["corners"]) == len(cell["gaugePhases"]) == 4
        phases = []
        for index, ((a, b), corner, alpha) in enumerate(zip(indices, cell["corners"], cell["gaugePhases"])):
            strict(corner["index"], [a, b])
            close(corner["k"][0], k[b]); close(corner["k"][1], k[a])
            step = 2*math.pi/size
            close(corner["unwrappedK"][0], k[i]+(step if index in (1, 2) else 0))
            close(corner["unwrappedK"][1], k[j]+(step if index in (2, 3) else 0))
            expected = strength*(math.sin(k[b])+.37*math.cos(k[a])+.23*math.sin(k[a]+k[b]))
            close(alpha, expected, "actual corner gauge phase")
            phases.append(alpha)
        raw = [complex_pair(v) for v in cell["before"]["rawForwardOverlaps"]]
        changed = [complex_pair(v) for v in cell["after"]["rawForwardOverlaps"]]
        assert len(raw) == len(changed) == 4
        independent = [rx[j][i], ry[j][(i+1) % size], rx[(j+1) % size][i], ry[j][i]]
        for edge, ((start, end), a, b, ref) in enumerate(zip(FORWARD, raw, changed, independent)):
            close(abs(a), abs(ref), f"edge {edge} magnitude")
            close(abs(b), abs(a), f"edge {edge} gauge magnitude")
            expected = a*cmath.exp(1j*(phases[end]-phases[start]))
            close(abs(expected-b), 0, f"edge {edge} endpoint gauge law")
        for stage, values in [("before", raw), ("after", changed)]:
            factors = [values[0], values[1], values[2].conjugate(), values[3].conjugate()]
            product = math.prod(z/abs(z) for z in factors)
            close(-cmath.phase(product), fluxes[j][i], "independent cell flux")
            if replay["bandIsolated"]:
                close(abs(complex_pair(cell[stage]["loop"])-product), 0, "actual loop product")
                close(cell[stage]["fluxRad"], -cmath.phase(product), "actual minus-Arg flux")
            else:
                assert cell[stage]["loop"] is None and cell[stage]["fluxRad"] is None


STRICT_OUTPUT_KEYS = {"model", "parameters", "convention", "schemaVersion", "mesh", "convergenceIndex",
                      "complexEncoding", "linkThreshold", "sewing", "orientation", "id", "anchor", "index"}


def compare_output(saved, current, path="result", key=""):
    if key in STRICT_OUTPUT_KEYS:
        strict(saved, current, path)
    elif key == "rawForwardOverlaps":
        # LAPACK may choose a different U(1) phase at each QWZ vertex.
        # verify_result additionally checks the complete closed product and
        # the actual known before->after endpoint phase law, so this does not
        # allow four arbitrary independent edge phases.
        assert isinstance(saved, list) and isinstance(current, list) and len(saved) == len(current) == 4
        for index, (a, b) in enumerate(zip(saved, current)):
            close(abs(complex_pair(a)), abs(complex_pair(b)), f"{path}[{index}] magnitude")
    elif isinstance(current, (int, float)) and not isinstance(current, bool):
        close(saved, current, path)
    elif isinstance(current, dict):
        assert isinstance(saved, dict) and saved.keys() == current.keys(), f"{path}: fields differ"
        for name in current:
            compare_output(saved[name], current[name], f"{path}.{name}", name)
    elif isinstance(current, list):
        assert isinstance(saved, list) and len(saved) == len(current), f"{path}: shape differs"
        for index, value in enumerate(current):
            compare_output(saved[index], value, f"{path}[{index}]")
    else:
        strict(saved, current, path)


def compare_asset(saved, current):
    assert isinstance(saved, dict) and saved.keys() == current.keys()
    for key in current:
        if key != "cases":
            strict(saved[key], current[key], key)
    assert isinstance(saved["cases"], list) and len(saved["cases"]) == len(current["cases"])
    for index, (stored, row) in enumerate(zip(saved["cases"], current["cases"])):
        strict(list(stored), list(row), f"cases[{index}] fields")
        strict(stored["id"], row["id"], "case id")
        strict(stored["input"], row["input"], "case input")
        verify_result(stored["result"])
        compare_output(stored["result"], row["result"])


def compact_result(result):
    result = copy.deepcopy(result)
    keep = ["model", "parameters", "convention", "topology", "convergence", "gauge", "checks", "fhsReplay"]
    compact = {key: result[key] for key in keep}
    compact["topology"].pop("reason")
    compact["topology"].pop("gapFormula")
    compact["gauge"].pop("meaning")
    compact["heatmap"] = {key: result["heatmap"][key] for key in ["kx", "ky", "orientation"]}
    compact["selection"] = {key: result["selection"][key] for key in
                            ["kx", "ky", "gap", "valid", "gxx", "gxy", "gyy", "metricTrace", "berryCurvature"]}
    return compact


def reference():
    cases = []
    for name, mass in MODELS:
        payload = dict(model="qwz", mass=mass, energyScale=1, t1=.6, t2=1, mesh=9,
                       pathSamples=31, gaugeStrength=2, kx=0, ky=0)
        result = compact_result(run("quantum_geometry_lab", payload))
        verify_result(result)
        cases.append(dict(id=name, input=payload, result=result))
    hashes = {name: hashlib.sha256(utf8_lf_bytes((ROOT/name).read_text(encoding="utf-8"))).hexdigest()
              for name in ["dist/python/quantum_geometry_lab.py", "dist/python/browser_api.py"]}
    return dict(format="production-api-bounded-fhs-plaquette-v1", action="quantum_geometry_lab",
                generator="scripts/check-fhs-plaquette-reference.py --write",
                sourceHashAlgorithm="sha256", sourceHashNormalization="utf8-lf-v1", sourceHashes=hashes,
                outputComparison=dict(absoluteTolerance=ATOL, relativeTolerance=RTOL,
                                      phasePolicy="QWZ raw links are compared modulo consistent vertex U(1) frames; magnitudes, closed products and actual before/after endpoint phase laws are checked. Metadata, inputs and structure are exact."),
                scope="Four actual QWZ API results, base N=9 / convergence[0], s=2, identity sewing; closed-gap loop and flux remain null.",
                cases=cases)


def contract_checks(data):
    strict(utf8_lf_bytes("a\r\nb\rc\n"), utf8_lf_bytes("a\nb\nc\n"))
    rounded = copy.deepcopy(data)
    rounded["cases"][0]["result"]["selection"]["gxx"] += 5e-15
    compare_asset(rounded, data)
    reframed = copy.deepcopy(data)
    cell = reframed["cases"][0]["result"]["fhsReplay"]["cells"][0]
    beta = [.2, .5, -.4, .7]
    for stage in ["before", "after"]:
        for edge, (start, end) in enumerate(FORWARD):
            changed = complex_pair(cell[stage]["rawForwardOverlaps"][edge])*cmath.exp(1j*(beta[end]-beta[start]))
            cell[stage]["rawForwardOverlaps"][edge] = [changed.real, changed.imag]
    compare_asset(reframed, data)
    rejected = []
    for change in ["input", "metadata", "numeric", "raw-magnitude", "raw-independent-phase", "shape", "boolean", "null", "index"]:
        altered = copy.deepcopy(data)
        row = altered["cases"][0]
        result = row["result"]
        cell = result["fhsReplay"]["cells"][0]
        if change == "input": row["input"]["mass"] += 1e-15
        elif change == "metadata": altered["sourceHashNormalization"] = "raw-bytes"
        elif change == "numeric": result["selection"]["gxx"] += 1e-8
        elif change == "raw-magnitude": cell["before"]["rawForwardOverlaps"][0][0] += 1e-5
        elif change == "raw-independent-phase":
            for stage in ["before", "after"]:
                z = complex_pair(cell[stage]["rawForwardOverlaps"][0])*cmath.exp(.2j)
                cell[stage]["rawForwardOverlaps"][0] = [z.real, z.imag]
        elif change == "shape": cell["corners"].pop()
        elif change == "boolean": result["fhsReplay"]["bandIsolated"] = 1
        elif change == "null": altered["cases"][3]["result"]["fhsReplay"]["cells"][0]["before"]["loop"] = [1, 0]
        elif change == "index": cell["corners"][0]["index"][0] += 1
        try:
            compare_asset(altered, data)
        except (AssertionError, IndexError):
            rejected.append(change)
    assert len(rejected) == 9, f"A material change was accepted: {rejected}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = reference()
    contract_checks(data)
    if args.write:
        ASSET.write_text(PREFIX+json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False)+SUFFIX, encoding="utf-8")
    else:
        source = ASSET.read_text(encoding="utf-8")
        assert source.startswith(PREFIX) and source.endswith(SUFFIX)
        compare_asset(json.loads(source[len(PREFIX):-len(SUFFIX)]), data)
    print(json.dumps(dict(ok=True, apiCases=len(data["cases"]), cells=8, independentAnalyticGrid=9,
                          sourceHashNormalization=data["sourceHashNormalization"], sourceHashes=data["sourceHashes"],
                          rejectedComparisonMutations=9, consistentVertexGaugeAccepted=True)))


if __name__ == "__main__":
    main()
