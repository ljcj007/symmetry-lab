"""Capture two bounded 001 slab cases from the actual public Python API.

This is a finite teaching reference, not an independent layer-group catalogue.
Run with the site's scientific dependencies on PYTHONPATH.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'dist/python'))
import browser_api

BASE = dict(face='001', layers=4, bulk='mono', cut=0, interface='same',
            termination='same', registry=0, pathEnd=.5)
SOURCES = ('dist/python/symmetry_frontiers.py', 'dist/python/browser_api.py',
           'dist/data/frontiers-materials.json')


def normalized_source_bytes(text):
    """utf8-lf-v1: decode UTF-8, normalize CRLF/CR to LF, encode UTF-8."""
    return text.replace('\r\n', '\n').replace('\r', '\n').encode('utf-8')


def build():
    cases = {}
    for name, termination in [('symmetric', 'same'), ('marker', 'marker')]:
        payload = BASE | {'termination': termination}
        result = browser_api.run('layer_symmetry_lab', payload)
        geometry = result['geometry']
        cases[name] = dict(input=payload, positions=geometry['unit'],
                           labels=geometry['labels'][:4], lattice=geometry['lattice'],
                           normal=geometry['normal'], operations=result['operations'],
                           operationCount=len(result['operations']),
                           normalFlipCount=sum(op['flipsNormal'] for op in result['operations']))
    return dict(format='real-python-layer-actions-reference-v1',
                action='layer_symmetry_lab', module='layers',
                scope='fixed-001-four-layer-cubic-parent-inherited-operations',
                lengthUnit='cubic-parent-lattice-constant',
                coordinateConvention='Cartesian columns; lattice basis vectors are columns',
                generator='scripts/build-layer-actions-reference.py',
                sourceHashNormalization='utf8-lf-v1',
                sourceHashes={path: hashlib.sha256(normalized_source_bytes(
                                  (ROOT / path).read_text(encoding='utf-8'))).hexdigest()
                              for path in SOURCES}, cases=cases)


if __name__ == '__main__':
    target = ROOT / 'dist/layer-actions-reference.js'
    target.write_text('// Generated by scripts/build-layer-actions-reference.py from browser_api.run.\n'
                      'export const LAYER_ACTIONS_REFERENCE = Object.freeze('
                      + json.dumps(build(), ensure_ascii=True, sort_keys=True, indent=2)
                      + ');\n', encoding='utf-8', newline='\n')
    print(target.name)
