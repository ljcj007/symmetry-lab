def build(check=False):
    path = ROOT / 'dist/data/lie-derivations.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    owned = {item['id'] for item in items}
    assert len(items) == len(owned) == 4
    others = [item for item in data['exercises'] if item['id'] not in owned]
    assert len(others) >= 40, 'Retain all introductory and previous application exercises'
    data['exercises'] = [*others, *items]
    assert len({item['id'] for item in data['exercises']}) == len(data['exercises'])
    data['description'] = (f"{len(data['exercises'])} 道引导练习：从 U(1)、幺正矩阵、生成元与权图基础，"
                           "走向物理应用、精确 CG、Racah 与高维四体重耦合。每题附提示、分步推导、"
                           "反例和独立判断；可用时联动对应实验。")
    body = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    if check:
        assert path.read_text(encoding='utf-8') == body, 'Advanced derivations are stale; regenerate them'
    else:
        path.write_text(body, encoding='utf-8', newline='\n')
    return data


