"""Reproduce bounded SSH teaching selections through the production browser API.

--write refreshes only the independent teaching asset. The default/--check path
verifies that asset and independently checks the two-component algebra.
"""
import argparse
import copy
import hashlib
import json
import math
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / ".openai/local-python-deps"))
sys.path.insert(0, str(ROOT / "dist/python"))
os.environ["PYTHONDONTWRITEBYTECODE"] = "1"
from browser_api import run
import numpy as np

BASES = [0, 0.6]
STRENGTHS = [0, 2, 4]
DELTAS = [0.02, 0.1, 0.5, 2]
ASSET = ROOT / "dist/geometry-actions-reference.js"
PREFIX = "// Generated by scripts/check-geometry-actions-reference.py --write.\nexport const GEOMETRY_ACTIONS_REFERENCE="
SUFFIX = ";\n"
OUTPUT_ATOL = 2e-14
OUTPUT_RTOL = 2e-14


def utf8_lf_bytes(text):
    """utf8-lf-v1: decode UTF-8, normalize CRLF/CR to LF, encode UTF-8."""
    return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


def strict_equal(saved, current, path):
    """Metadata and model inputs remain exact, including field/type/shape."""
    assert type(saved) is type(current), f"{path}: field type differs"
    if isinstance(current, dict):
        assert saved.keys() == current.keys(), f"{path}: fields differ"
        for key in current:
            strict_equal(saved[key], current[key], f"{path}.{key}")
    elif isinstance(current, list):
        assert len(saved) == len(current), f"{path}: length differs"
        for index, value in enumerate(current):
            strict_equal(saved[index], value, f"{path}[{index}]")
    else:
        assert saved == current, f"{path}: exact value differs"


def output_equal(saved, current, path):
    """Only numeric API output leaves get a stated floating-point tolerance."""
    if isinstance(current, (int, float)) and not isinstance(current, bool):
        assert isinstance(saved, (int, float)) and not isinstance(saved, bool), f"{path}: expected a number"
        assert math.isfinite(saved) and math.isfinite(current), f"{path}: nonfinite output"
        assert math.isclose(saved, current, abs_tol=OUTPUT_ATOL, rel_tol=OUTPUT_RTOL), f"{path}: output differs beyond tolerance"
    elif isinstance(current, dict):
        assert isinstance(saved, dict) and saved.keys() == current.keys(), f"{path}: output fields differ"
        for key in current:
            output_equal(saved[key], current[key], f"{path}.{key}")
    elif isinstance(current, list):
        assert isinstance(saved, list) and len(saved) == len(current), f"{path}: output shape differs"
        for index, value in enumerate(current):
            output_equal(saved[index], value, f"{path}[{index}]")
    else:
        strict_equal(saved, current, path)


def compare_asset(saved, current):
    assert isinstance(saved, dict) and saved.keys() == current.keys(), "root: fields differ"
    for key in current:
        if key != "selections":
            strict_equal(saved[key], current[key], key)
    assert isinstance(saved["selections"], list) and len(saved["selections"]) == len(current["selections"]), "selections: length differs"
    for index, row in enumerate(current["selections"]):
        stored = saved["selections"][index]
        assert isinstance(stored, dict) and stored.keys() == row.keys(), f"selections[{index}]: fields differ"
        for key in row:
            if key == "selection":
                output_equal(stored[key], row[key], f"selections[{index}].selection")
            else:
                strict_equal(stored[key], row[key], f"selections[{index}].{key}")


def check_comparison_contract(data):
    assert utf8_lf_bytes("a\r\nb\rc\n") == utf8_lf_bytes("a\nb\nc\n")
    rounded = copy.deepcopy(data)
    rounded["selections"][0]["selection"]["gxx"] += 5e-15
    compare_asset(rounded, data)
    rejected = []
    for change in ["output", "input", "metadata", "fields", "shape", "boolean", "nonfinite", "eigenvector-sign"]:
        altered = copy.deepcopy(data)
        row = altered["selections"][0]
        if change == "output": row["selection"]["gxx"] += 1e-8
        elif change == "input": row["input"]["t1"] = 1e-15
        elif change == "metadata": altered["sourceHashNormalization"] = "raw-bytes"
        elif change == "fields": del row["selection"]["projector"]
        elif change == "shape": row["selection"]["projector"].pop()
        elif change == "boolean": row["selection"]["valid"] = 1
        elif change == "nonfinite": row["selection"]["gxx"] = float("nan")
        elif change == "eigenvector-sign": row["selection"]["eigenvector"] = [[-x for x in pair] for pair in row["selection"]["eigenvector"]]
        try:
            compare_asset(altered, data)
        except AssertionError:
            rejected.append(change)
    assert len(rejected) == 8, f"Comparison contract accepted a material change: {rejected}"


def unpack(values):
    return np.asarray(values)[..., 0] + 1j * np.asarray(values)[..., 1]


def reference():
    selections = []
    for base in BASES:
        for strength in STRENGTHS:
            for delta in [0] + DELTAS:
                k = base + delta
                inputs = dict(model="ssh", mass=-1, energyScale=1, t1=0, t2=1,
                              mesh=9, pathSamples=31, gaugeStrength=strength, kx=k, ky=0)
                selected = run("quantum_geometry_lab", inputs)["selection"]
                # Store numerical output fields only; no translated core prose.
                keep = ["kx", "ky", "gap", "valid", "gxx", "phase", "eigenvector",
                        "transformedEigenvector", "projector"]
                selections.append(dict(base=base, strength=strength, delta=delta,
                                       input=inputs, selection={key: selected[key] for key in keep}))
                # Direct independent lower-band eigenpair for this fixed H.
                # On these 30 selections at k>=0 we require the declared smooth
                # phase (-1,exp(ik))/sqrt(2), not only projector equivalence.
                # This is not an assumption about arbitrary eigensolver grids.
                u = np.array([-1, np.exp(1j * k)]) / math.sqrt(2)
                du = np.array([0, 1j * np.exp(1j * k)]) / math.sqrt(2)
                H = np.array([[0, np.exp(-1j * k)], [np.exp(1j * k), 0]])
                P = np.outer(u, u.conj())
                np.testing.assert_allclose(H @ u, -u, rtol=0, atol=2e-14)
                np.testing.assert_allclose(unpack(selected["projector"]), P, rtol=0, atol=2e-14)
                np.testing.assert_allclose(unpack(selected["eigenvector"]), u, rtol=0, atol=2e-14)
                alpha = strength * (math.sin(k) + 0.37 * math.cos(2 * k))
                slope = strength * (math.cos(k) - 0.74 * math.sin(2 * k))
                gauged = np.exp(1j * alpha) * u
                np.testing.assert_allclose(unpack(selected["transformedEigenvector"]), gauged, rtol=0, atol=2e-14)
                gauged_derivative = np.exp(1j * alpha) * (du + 1j * slope * u)
                projected = (np.eye(2) - P) @ gauged_derivative
                assert abs(np.vdot(projected, projected).real - 0.25) < 2e-14
                assert abs(np.vdot(gauged_derivative, gauged_derivative).real - (0.5 + slope + slope**2)) < 2e-13
                assert abs(selected["gxx"] - 0.25) < 2e-14
                assert abs(selected["gap"] - 2) < 2e-14 and selected["valid"]
    for base in BASES:
        for strength in STRENGTHS:
            rows = [r for r in selections if r["base"] == base and r["strength"] == strength]
            u = unpack(rows[0]["selection"]["transformedEigenvector"])
            for row in rows[1:]:
                v = unpack(row["selection"]["transformedEigenvector"])
                delta = row["delta"]
                fidelity = abs(np.vdot(u, v))**2
                assert abs(fidelity - math.cos(delta/2)**2) < 3e-14
                # Independent finite-difference contraction of the real API P.
                difference = (unpack(row["selection"]["projector"]) - unpack(rows[0]["selection"]["projector"])) / delta
                finite = (np.trace(difference @ difference).real) / 2
                assert abs(finite - math.sin(delta/2)**2 / delta**2) < 2e-12
    hashes = {name: hashlib.sha256(utf8_lf_bytes((ROOT / name).read_text(encoding="utf-8"))).hexdigest()
              for name in ["dist/python/quantum_geometry_lab.py", "dist/python/browser_api.py"]}
    return dict(format="production-api-bounded-ssh-reference-v1", action="quantum_geometry_lab",
                generator="scripts/check-geometry-actions-reference.py --write",
                sourceHashes=hashes, sourceHashAlgorithm="sha256", sourceHashNormalization="utf8-lf-v1",
                outputComparison=dict(absoluteTolerance=OUTPUT_ATOL, relativeTolerance=OUTPUT_RTOL,
                                      scope="Numeric selection output only; field structure, inputs and provenance are exact."),
                eigenvectorScope="Only these 30 nonnegative-k SSH selections are checked against the smooth representative (-1,exp(ik))/sqrt(2). No arbitrary eigenvector phase jumps are accepted or assumed smooth.",
                bases=BASES, strengths=STRENGTHS, deltas=DELTAS,
                convention="Fixed periodic orbital basis; lower band; k in radians; t1=0,t2=1; gap=2; A=i<u|du>.",
                selections=selections)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = reference()
    check_comparison_contract(data)
    if args.write:
        ASSET.write_text(PREFIX + json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False) + SUFFIX, encoding="utf-8")
    else:
        source = ASSET.read_text(encoding="utf-8")
        assert source.startswith(PREFIX) and source.endswith(SUFFIX)
        saved = json.loads(source[len(PREFIX):-len(SUFFIX)])
        compare_asset(saved, data)
    print(json.dumps(dict(ok=True, apiSelections=len(data["selections"]), bases=BASES, strengths=STRENGTHS,
                          deltas=DELTAS, gxx=0.25, sourceHashes=data["sourceHashes"],
                          sourceHashNormalization=data["sourceHashNormalization"],
                          outputComparison=data["outputComparison"], rejectedComparisonMutations=8)))


if __name__ == "__main__":
    main()
