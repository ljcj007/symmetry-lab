"""Build display aliases from explicit type-I magnetic group notation."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
def read(name):
    return json.loads((ROOT / 'dist/data' / name).read_text(encoding='utf-8'))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sg, mg = read('space-groups.json')['groups'], read('magnetic-groups.json')['groups']
    atlas, pg = read('symmetry-course-atlas.json'), read('pointgroup-atlas.json')['groups']
    reference = {g['family']: g for g in mg if g['type'] == 1}
    assert len(reference) == 230
    aliases = {}
    for g in sg:
        for field in ('symbol', 'bcSymbol'):
            raw, canonical = g[field], reference[g['number']][field]
            if raw in aliases and aliases[raw] != canonical:
                raise ValueError('Ambiguous compact display alias: ' + raw)
            aliases[raw] = canonical
            aliases[canonical] = canonical
    hm = set(aliases)
    for g in mg:
        hm.update(g[k] for k in ('symbol', 'bcSymbol', 'ogSymbol'))
    hm.update(g['symbol'] for g in atlas['magneticPointGroups'])
    hm.update(g['hm'] for g in pg)
    ops = {o['name'] for g in sg + mg for o in g['operations']}
    rows = [('hmAliases', aliases), ('knownHmSymbols', sorted(hm)),
            ('knownOperations', sorted(ops)),
            ('knownSchoenflies', sorted({g['schoenflies'] for g in pg}))]
    text = '// Generated by scripts/build-crystal-symbol-data.py; original identifiers remain unchanged.\n'
    for name, value in rows:
        text += 'export const ' + name + '=' + json.dumps(value, ensure_ascii=True, separators=(',', ':')) + ';\n'
    path = ROOT / 'dist/crystal-symbol-data.js'
    if args.check:
        assert path.read_text(encoding='utf-8') == text, 'Stale display aliases'
    else:
        path.write_text(text, encoding='utf-8', newline='\n')
    print(f'Crystal display aliases: {len(aliases)} aliases, {len(hm)} HM symbols, {len(ops)} operations')

if __name__ == '__main__':
    main()
