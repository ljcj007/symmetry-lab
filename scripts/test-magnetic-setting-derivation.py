# Exact antitranslation subgroup on a two-sublattice periodic classical field.
def compose(a, b):
    return ((a[0]+b[0]) % 2, a[1]+b[1])


def point_image(a):
    return a[0]


def field(x, L):
    twice = 2*x
    assert twice.denominator == 1
    sign = 1 if twice.numerator % 2 == 0 else -1
    return tuple(sign*value for value in L)


def apply(operation, x, L):
    epsilon, shift = operation
    return tuple((-1)**epsilon*value for value in field(x-shift, L))


