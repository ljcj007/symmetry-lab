def nullspace(a):
    rows = [list(row) for row in a]
    n = len(rows[0])
    pivots = []
    pivot_row = 0
    for col in range(n):
        choices = [i for i in range(pivot_row, len(rows)) if rows[i][col]]
        if not choices:
            continue
        i = choices[0]
        rows[pivot_row], rows[i] = rows[i], rows[pivot_row]
        value = rows[pivot_row][col]
        rows[pivot_row] = [v/value for v in rows[pivot_row]]
        for j in range(len(rows)):
            if j != pivot_row:
                value = rows[j][col]
                rows[j] = [v - value*u for v, u in zip(rows[j], rows[pivot_row])]
        pivots.append(col)
        pivot_row += 1
    basis = []
    for free in [col for col in range(n) if col not in pivots]:
        v = [F(0)]*n
        v[free] = F(1)
        for i, col in enumerate(pivots):
            v[col] = -rows[i][free]
        basis.append(tuple(v))
    return basis


def published_uniform_basis(name):
    text = ';'.join(step['formula'] for step in item['steps'])
    match = re.search(re.escape('M_('+name+')') + r'=\(([^)]+)\)', text)
    tokens = match[1].split(',')
    assert len(tokens) == 3
    directions = []
    for i, token in enumerate(tokens):
        if token == '0':
            continue
        assert token == 'M_'+'xyz'[i], token
        directions.append(tuple(F(int(i == j)) for j in range(3)))
    return directions


