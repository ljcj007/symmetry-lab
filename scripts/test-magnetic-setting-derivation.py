def matrix(rows):
    return tuple(tuple(F(value) for value in row) for row in rows)


def eye(n):
    return matrix([[int(i == j) for j in range(n)] for i in range(n)])


def add(a, b, sign=1):
    assert len(a) == len(b) and len(a[0]) == len(b[0])
    return tuple(tuple(x + sign*y for x, y in zip(row_a, row_b)) for row_a, row_b in zip(a, b))


def mm(a, b):
    assert len(a[0]) == len(b)
    return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(len(b)))
                       for j in range(len(b[0]))) for i in range(len(a)))


def scale(a, scalar):
    return tuple(tuple(F(scalar)*value for value in row) for row in a)


def inverse(a):
    n = len(a)
    assert len(a[0]) == n
    augmented = [list(row) + list(unit) for row, unit in zip(a, eye(n))]
    for col in range(n):
        pivot = next(i for i in range(col, n) if augmented[i][col])
        augmented[col], augmented[pivot] = augmented[pivot], augmented[col]
        value = augmented[col][col]
        augmented[col] = [v/value for v in augmented[col]]
        for i in range(n):
            if i != col:
                value = augmented[i][col]
                augmented[i] = [v - value*u for v, u in zip(augmented[i], augmented[col])]
    return matrix([row[n:] for row in augmented])


def column(values):
    return matrix([[value] for value in values])


class Formula:
    """Restricted matrix expressions with implicit products and exact inverses."""
    def __init__(self, source, symbols):
        self.tokens = re.findall(r'[PRItp]|⁻¹|[()\[\]+−-]', source)
        assert ''.join(self.tokens) == re.sub(r'\s+', '', source), source
        self.index = 0
        self.symbols = symbols

    def next(self):
        return self.tokens[self.index] if self.index < len(self.tokens) else None

    def factor(self):
        token = self.next()
        self.index += 1
        if token in ('(', '['):
            result = self.expression()
            assert self.next() == (')' if token == '(' else ']')
            self.index += 1
        else:
            assert token in self.symbols, token
            result = self.symbols[token]
        while self.next() == '⁻¹':
            self.index += 1
            result = inverse(result)
        return result

    def product(self):
        result = self.factor()
        while self.next() in ('P', 'R', 'I', 't', 'p', '(', '['):
            result = mm(result, self.factor())
        return result

    def expression(self):
        result = self.product()
        while self.next() in ('+', '−', '-'):
            op = self.next()
            self.index += 1
            result = add(result, self.product(), 1 if op == '+' else -1)
        return result

    def evaluate(self):
        result = self.expression()
        assert self.index == len(self.tokens)
        return result


